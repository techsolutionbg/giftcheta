<?php
declare(strict_types=1);
use Giftcheta\Core\Application;
use Giftcheta\Core\Config;
use Giftcheta\Core\Logger;
use Giftcheta\Core\Router;
use Giftcheta\Http\Controllers\HealthController;
use Giftcheta\Http\Controllers\StatusController;
use Giftcheta\Http\Middleware\ErrorHandler;
use Giftcheta\Http\Request;
use Giftcheta\Modules\Admin\AuthApi;
use Giftcheta\Modules\Admin\CatalogApi;
require dirname(__DIR__) . '/vendor/autoload.php';
Config::loadEnvironment(dirname(__DIR__) . '/.env');
$config = Config::fromDirectory(dirname(__DIR__) . '/config');
$logger = new Logger(dirname(__DIR__) . '/storage/logs/app.log', $config->get('app.log_level', 'error'));
$router = new Router();
$router->get('/api/v1/health', [HealthController::class, 'show']);
$router->get('/api/v1/status', [StatusController::class, 'show']);
$database = \Giftcheta\Core\Database::connect($config);
$authApi = new AuthApi($database, $config);
$catalogApi = new CatalogApi($database, $authApi, dirname(__DIR__));
$router->get('/api/v1/admin/auth/csrf', fn (Request $request) => $authApi->csrf($request));
$router->post('/api/v1/admin/auth/login', fn (Request $request) => $authApi->login($request));
$router->post('/api/v1/admin/auth/logout', fn (Request $request) => $authApi->logout($request));
$router->get('/api/v1/admin/me', fn (Request $request) => $authApi->me($request));
$router->get('/api/v1/admin/categories', fn (Request $request) => $catalogApi->categories($request));
$router->get('/api/v1/admin/stats', fn (Request $request) => $catalogApi->stats($request));
$router->post('/api/v1/admin/categories', fn (Request $request) => $catalogApi->createCategory($request));
$router->patch('/api/v1/admin/categories/{id}', fn (Request $request, $config, array $params) => $catalogApi->updateCategory($request, $params));
$router->delete('/api/v1/admin/categories/{id}', fn (Request $request, $config, array $params) => $catalogApi->deleteCategory($request, $params));
$router->post('/api/v1/admin/categories/{id}/image', fn (Request $request, $config, array $params) => $catalogApi->uploadCategoryImage($request, $params));
$router->delete('/api/v1/admin/categories/{id}/image', fn (Request $request, $config, array $params) => $catalogApi->deleteCategoryImage($request, $params));
$router->get('/api/v1/admin/products', fn (Request $request) => $catalogApi->products($request));
$router->post('/api/v1/admin/products/bulk', fn (Request $request) => $catalogApi->bulkProducts($request));
$router->post('/api/v1/admin/products', fn (Request $request) => $catalogApi->createProduct($request));
$router->get('/api/v1/admin/products/{id}', fn (Request $request, $config, array $params) => $catalogApi->product($request, $params));
$router->patch('/api/v1/admin/products/{id}', fn (Request $request, $config, array $params) => $catalogApi->updateProduct($request, $params));
$router->delete('/api/v1/admin/products/{id}', fn (Request $request, $config, array $params) => $catalogApi->deleteProduct($request, $params));
$router->post('/api/v1/admin/products/{id}/variants', fn (Request $request, $config, array $params) => $catalogApi->createVariant($request, $params));
$router->patch('/api/v1/admin/variants/{id}', fn (Request $request, $config, array $params) => $catalogApi->updateVariant($request, $params));
$router->delete('/api/v1/admin/variants/{id}', fn (Request $request, $config, array $params) => $catalogApi->deleteVariant($request, $params));
$router->post('/api/v1/admin/products/{id}/fields', fn (Request $request, $config, array $params) => $catalogApi->createField($request, $params));
$router->patch('/api/v1/admin/fields/{id}', fn (Request $request, $config, array $params) => $catalogApi->updateField($request, $params));
$router->delete('/api/v1/admin/fields/{id}', fn (Request $request, $config, array $params) => $catalogApi->deleteField($request, $params));
$router->post('/api/v1/admin/products/{id}/stock', fn (Request $request, $config, array $params) => $catalogApi->adjustStock($request, $params));
$router->post('/api/v1/admin/products/{id}/variants/{variant_id}/stock', fn (Request $request, $config, array $params) => $catalogApi->adjustStock($request, ['id'=>$params['id'],'variant_id'=>$params['variant_id']]));
$router->post('/api/v1/admin/products/{id}/images', fn (Request $request, $config, array $params) => $catalogApi->uploadImage($request, $params));
$router->patch('/api/v1/admin/images/{id}', fn (Request $request, $config, array $params) => $catalogApi->updateImage($request, $params));
$router->delete('/api/v1/admin/images/{id}', fn (Request $request, $config, array $params) => $catalogApi->deleteImage($request, $params));
$app = new Application($router, $config, $logger, [new ErrorHandler($logger, $config)]);
$app->run(Request::fromGlobals());
